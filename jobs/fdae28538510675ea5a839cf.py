from manim import *
import numpy as np

class AetherLabScene(Scene):
    def construct(self):
        # BEAT A1.B1 | 0.00-4.00 s
        rail = Line(LEFT * 6.2, RIGHT * 6.2, color=GRAY, stroke_width=8).shift(DOWN * 1.2)
        ties = VGroup(*[Line(UP * 0.12, DOWN * 0.12, color=GRAY, stroke_width=3).move_to(np.array([x, -1.2, 0])) for x in np.arange(-6, 6.5, 0.6)])
        ties.set_stroke(opacity=0.35)
        def make_cart(col, mass_txt):
            body = Rectangle(width=1.5, height=0.7, color=col, fill_opacity=0.9, stroke_width=3)
            body.set_z_index(2)
            w1 = Circle(radius=0.14, color=WHITE, fill_opacity=1).move_to(body.get_bottom() + LEFT * 0.4 + DOWN * 0.14)
            w2 = Circle(radius=0.14, color=WHITE, fill_opacity=1).move_to(body.get_bottom() + RIGHT * 0.4 + DOWN * 0.14)
            lab = Text(mass_txt, color=WHITE, font_size=30).move_to(body.get_center())
            g = VGroup(body, w1, w2, lab)
            return g
        cart1 = make_cart(BLUE, "3 кг")
        cart2 = make_cart(RED, "1 кг")
        cart1.move_to(np.array([-4.2, -0.45, 0]))
        cart2.move_to(np.array([0.6, -0.45, 0]))
        vlab1 = Text("4 м/с", color=BLUE, font_size=30).next_to(cart1, UP, buff=0.15)
        vlab2 = Text("0 м/с", color=RED, font_size=30).next_to(cart2, UP, buff=0.15)
        p_title = Text("p = 12 кг·м/с", color=WHITE, font_size=32).to_edge(UP, buff=0.4)
        p_title.set_z_index(5)
        self.play(Create(rail), Create(ties), FadeIn(cart1), FadeIn(cart2), FadeIn(p_title), run_time=1.0)
        self.play(cart1.animate.shift(RIGHT * 2.6), vlab1.animate.shift(RIGHT * 2.6), FadeIn(vlab1), FadeIn(vlab2), run_time=2.2, rate_func=linear)
        self.wait(0.6)
        # BEAT A2.B1 | 4.00-7.00 s
        q = Text("Что будет после удара?", color=WHITE, font_size=34).move_to(UP * 1.8)
        eq_pm = MathTex(r"p = m v", color=WHITE, font_size=44).next_to(q, DOWN, buff=0.2)
        pred = VGroup(q, eq_pm)
        self.play(FadeIn(pred, shift=DOWN * 0.2), run_time=0.7)
        self.wait(1.9)
        # BEAT A2.B2 | 7.00-10.00 s
        before_label = Text("До: ", color=WHITE, font_size=38)
        before_eq = MathTex(r"p = 3 \cdot 4 + 1 \cdot 0 = 12", color=WHITE, font_size=38)
        before = VGroup(before_label, before_eq).arrange(RIGHT, buff=0.2).move_to(DOWN * 0.5)
        self.play(FadeOut(pred), FadeIn(before, shift=UP * 0.2), run_time=0.7)
        self.wait(2.0)
        # BEAT A3.B1 | 10.00-14.00 s
        self.play(FadeOut(before), FadeOut(vlab1), FadeOut(vlab2), run_time=0.4)
        impact_point = cart2.get_left() + LEFT * 0.2 + UP * 0.3
        flash_dot = Dot(impact_point, color=WHITE, radius=0.08)
        self.play(Flash(flash_dot, color=WHITE), cart1.animate.shift(RIGHT * 0.9), cart2.animate.shift(RIGHT * 0.6), run_time=0.6)
        self.play(cart1.animate.shift(RIGHT * 0.7), cart2.animate.shift(RIGHT * 3.0), run_time=2.2, rate_func=linear)
        self.wait(0.6)
        # BEAT A3.B2 | 14.00-18.00 s
        arr1 = Arrow(start=ORIGIN, end=RIGHT * 0.9, color=BLUE, buff=0, stroke_width=6).next_to(cart1, UP, buff=0.15)
        arr2 = Arrow(start=ORIGIN, end=RIGHT * 2.2, color=RED, buff=0, stroke_width=6).next_to(cart2, UP, buff=0.15)
        tag1 = Text("v1' = 2 м/с", color=BLUE, font_size=30).next_to(arr1, UP, buff=0.1)
        tag2 = Text("v2' = 6 м/с", color=RED, font_size=30).next_to(arr2, UP, buff=0.1)
        after_tags = VGroup(arr1, tag1, arr2, tag2)
        self.play(LaggedStart(Create(arr1), FadeIn(tag1), Create(arr2), FadeIn(tag2), lag_ratio=0.25), run_time=1.2)
        self.wait(2.4)
        # BEAT A4.B1 | 18.00-22.00 s
        stage = VGroup(rail, ties, cart1, cart2, after_tags, p_title)
        self.play(FadeOut(stage), run_time=0.5)
        eq_a = MathTex(r"v_1' = \frac{m_1-m_2}{m_1+m_2}v_1", color=WHITE, font_size=42).move_to(UP * 0.8)
        eq_b = MathTex(r"v_2' = \frac{2m_1}{m_1+m_2}v_1", color=WHITE, font_size=42).next_to(eq_a, DOWN, buff=0.35)
        laws = VGroup(eq_a, eq_b)
        self.play(FadeIn(laws, shift=UP * 0.2), run_time=0.8)
        eq_a2 = MathTex(r"v_1' = \frac{3-1}{3+1}\cdot 4 = 2", color=WHITE, font_size=42).move_to(eq_a.get_center())
        eq_b2 = MathTex(r"v_2' = \frac{2\cdot 3}{3+1}\cdot 4 = 6", color=WHITE, font_size=42).move_to(eq_b.get_center())
        laws2 = VGroup(eq_a2, eq_b2)
        self.play(TransformMatchingTex(laws, laws2), run_time=1.2)
        self.wait(1.4)
        # BEAT A4.B2 | 22.00-26.00 s
        check = MathTex(r"p' = 3 \cdot 2 + 1 \cdot 6 = 12", color=WHITE, font_size=42).move_to(DOWN * 1.2)
        ok = Text("Совпало с До ✓", color=GREEN, font_size=32).next_to(check, DOWN, buff=0.25)
        self.play(LaggedStart(FadeIn(check, shift=UP * 0.2), FadeIn(ok, shift=UP * 0.15), lag_ratio=0.5), run_time=1.3)
        self.wait(2.2)
        # BEAT A5.B1 | 26.00-30.00 s
        self.play(FadeOut(laws2), FadeOut(check), FadeOut(ok), run_time=0.5)
        rail2 = Line(LEFT * 6.2, RIGHT * 6.2, color=GRAY, stroke_width=8).shift(DOWN * 1.6)
        c1h = make_cart(BLUE, "3 кг")
        c2h = make_cart(RED, "1 кг")
        c1h.move_to(np.array([-2.2, -0.85, 0]))
        c2h.move_to(np.array([1.6, -0.85, 0]))
        t1h = Text("2 м/с", color=BLUE, font_size=30).next_to(c1h, UP, buff=0.15)
        t2h = Text("6 м/с", color=RED, font_size=30).next_to(c2h, UP, buff=0.15)
        ribbon = Text("Импульс сохранился: 12 = 12", color=YELLOW, font_size=36).move_to(UP * 1.9)
        hero_eq = MathTex(r"3\cdot 4 = 3\cdot 2 + 1\cdot 6", color=WHITE, font_size=40).next_to(ribbon, DOWN, buff=0.25)
        hero = VGroup(rail2, c1h, c2h, t1h, t2h, ribbon, hero_eq)
        hero.scale_to_fit_width(12.0)
        hero.move_to(ORIGIN * 0.2)
        self.play(FadeIn(hero, shift=UP * 0.2), run_time=0.8)
        self.play(Flash(ribbon, color=YELLOW), Circumscribe(ribbon, color=YELLOW), run_time=0.8)
        t = ValueTracker(0.0)
        c1h.add_updater(lambda m: m.shift(RIGHT * 0.008))
        c2h.add_updater(lambda m: m.shift(RIGHT * 0.02))
        t1h.add_updater(lambda m: m.shift(RIGHT * 0.008))
        t2h.add_updater(lambda m: m.shift(RIGHT * 0.02))
        self.play(t.animate.set_value(1.0), run_time=2.5, rate_func=linear)
        c1h.clear_updaters()
        c2h.clear_updaters()
        t1h.clear_updaters()
        t2h.clear_updaters()