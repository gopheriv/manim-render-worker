from manim import *
import numpy as np
class AetherLabScene(Scene):
    def construct(self):
            # BEAT A1.B1 | 0.00-4.00 s
            title = Text("Два заряда напротив друг друга", font_size=32).to_edge(UP, buff=0.4)
            c1 = Circle(radius=0.55, color=BLUE, fill_opacity=0.9, stroke_width=3).move_to([-2.8, 0.5, 0])
            glow1 = Circle(radius=0.72, color=BLUE, fill_opacity=0.18, stroke_width=0).move_to(c1.get_center())
            lab1 = VGroup(Text("+", font_size=52), Text("q1 +2 нКл", font_size=30)).arrange(DOWN, buff=0.05)
            lab1.move_to(c1.get_center()+DOWN*1.25)
            c2 = Circle(radius=0.55, color=RED, fill_opacity=0.9, stroke_width=3).move_to([2.8, 0.5, 0])
            glow2 = Circle(radius=0.72, color=RED, fill_opacity=0.18, stroke_width=0).move_to(c2.get_center())
            lab2 = VGroup(Text("−", font_size=52), Text("q2 −3 нКл", font_size=30)).arrange(DOWN, buff=0.05)
            lab2.move_to(c2.get_center()+DOWN*1.25)
            ruler = Line([-2.25, -0.55, 0], [2.25, -0.55, 0], color=GRAY, stroke_width=3)
            tick1 = Line([-2.25, -0.7, 0], [-2.25, -0.4, 0], color=GRAY, stroke_width=3)
            tick2 = Line([2.25, -0.7, 0], [2.25, -0.4, 0], color=GRAY, stroke_width=3)
            rlab = Text("расстояние 10 см", font_size=30).next_to(ruler, DOWN, buff=0.15)
            self.play(LaggedStart(FadeIn(title), FadeIn(VGroup(glow1, c1, lab1)), FadeIn(VGroup(glow2, c2, lab2)), FadeIn(VGroup(ruler, tick1, tick2, rlab)), lag_ratio=0.2), run_time=1.2)
            self.wait(2.4)
            # BEAT A2.B1 | 4.00-7.00 s
            arr1 = Arrow(start=[-1.7, 0.5, 0], end=[-0.6, 0.5, 0], color=WHITE, stroke_width=8, buff=0)
            arr2 = Arrow(start=[1.7, 0.5, 0], end=[0.6, 0.5, 0], color=WHITE, stroke_width=8, buff=0)
            attr = Text("притяжение", font_size=30).move_to([0, 1.35, 0])
            self.play(LaggedStart(GrowArrow(arr1), GrowArrow(arr2), FadeIn(attr), lag_ratio=0.3), run_time=1.0)
            self.wait(1.6)
            # BEAT A2.B2 | 7.00-11.00 s
            law_title = Text("Закон Кулона", font_size=30).move_to([0, 2.9, 0])
            eq1 = MathTex(r"F = k \frac{q_1 q_2}{r^2}", font_size=44).next_to(law_title, DOWN, buff=0.15)
            eq1.set_z_index(2)
            self.play(FadeOut(title), FadeIn(law_title), FadeIn(eq1), run_time=0.9)
            self.wait(2.7)
            # BEAT A3.B1 | 11.00-16.00 s
            Ftrack = ValueTracker(0)
            flabel = Text("F =", font_size=32).move_to([-1.6, -2.2, 0])
            fnum = DecimalNumber(0, num_decimal_places=1, font_size=36).next_to(flabel, RIGHT, buff=0.2)
            funit = Text("мкН", font_size=30).next_to(fnum, RIGHT, buff=0.2)
            fnum.add_updater(lambda m: m.set_value(Ftrack.get_value()).next_to(flabel, RIGHT, buff=0.2))
            funit.add_updater(lambda m: m.next_to(fnum, RIGHT, buff=0.2))
            self.play(FadeIn(VGroup(flabel, fnum, funit)), run_time=0.5)
            self.play(AnimationGroup(c1.animate.shift(RIGHT*0.5), glow1.animate.shift(RIGHT*0.5), lab1.animate.shift(RIGHT*0.5), c2.animate.shift(LEFT*0.5), glow2.animate.shift(LEFT*0.5), lab2.animate.shift(LEFT*0.5), Ftrack.animate.set_value(5.4), run_time=3.0, rate_func=smooth))
            fnum.clear_updaters()
            funit.clear_updaters()
            fnum.set_value(5.4)
            fnum.next_to(flabel, RIGHT, buff=0.2)
            funit.next_to(fnum, RIGHT, buff=0.2)
            self.wait(1.1)
            # BEAT A4.B1 | 16.00-20.00 s
            self.play(FadeOut(VGroup(attr, flabel, fnum, funit)), run_time=0.4)
            eq2 = MathTex(r"|F| = 8{,}99\cdot 10^9 \cdot \frac{6\cdot 10^{-18}}{0{,}01}", font_size=36).move_to([0, -2.4, 0])
            sublab = Text("Подставляем числа в формулу", font_size=30).next_to(eq2, DOWN, buff=0.2)
            self.play(TransformMatchingTex(eq1, eq2), FadeIn(sublab), run_time=1.0)
            self.wait(2.6)
            # BEAT A4.B2 | 20.00-25.00 s
            eq3 = MathTex(r"|F| \approx 5{,}4\cdot 10^{-6}\, \text{N}", font_size=44).move_to([0, -1.7, 0])
            reslab = Text("Около пяти микроньютон", font_size=30).next_to(eq3, DOWN, buff=0.2)
            self.play(TransformMatchingTex(eq2, eq3), FadeOut(sublab), FadeIn(reslab), run_time=1.0)
            self.wait(4.0)
            # BEAT A5.B1 | 25.00-30.00 s
            self.play(FadeOut(VGroup(law_title, eq3, reslab, ruler, tick1, tick2, rlab, arr1, arr2, c1, glow1, lab1, c2, glow2, lab2)), run_time=0.5)
            h_eq = MathTex(r"F = k \frac{q_1 q_2}{r^2}", font_size=42).move_to([0, 2.6, 0])
            h_c1 = Circle(radius=0.55, color=BLUE, fill_opacity=0.9, stroke_width=3).move_to([-2.8, 0.6, 0])
            h_g1 = Circle(radius=0.72, color=BLUE, fill_opacity=0.18, stroke_width=0).move_to(h_c1.get_center())
            h_l1 = Text("q1 +2 нКл", font_size=30).next_to(h_c1, DOWN, buff=0.35)
            h_c2 = Circle(radius=0.55, color=RED, fill_opacity=0.9, stroke_width=3).move_to([2.8, 0.6, 0])
            h_g2 = Circle(radius=0.72, color=RED, fill_opacity=0.18, stroke_width=0).move_to(h_c2.get_center())
            h_l2 = Text("q2 −3 нКл", font_size=30).next_to(h_c2, DOWN, buff=0.35)
            h_a1 = Arrow(start=[-1.7, 0.6, 0], end=[-0.6, 0.6, 0], color=YELLOW, stroke_width=10, buff=0)
            h_a2 = Arrow(start=[1.7, 0.6, 0], end=[0.6, 0.6, 0], color=YELLOW, stroke_width=10, buff=0)
            plaque = RoundedRectangle(corner_radius=0.2, width=6.4, height=0.9, color=YELLOW, fill_opacity=0.22, stroke_color=YELLOW).move_to([0, -1.9, 0])
            ptxt = Text("Притяжение |F|≈5,4 мкН, r=10 см", font_size=30, color=YELLOW).move_to(plaque.get_center())
            hero = VGroup(h_eq, h_c1, h_g1, h_l1, h_c2, h_g2, h_l2, h_a1, h_a2, plaque, ptxt)
            hero.scale_to_fit_width(12.0)
            hero.move_to(ORIGIN)
            self.play(FadeIn(hero), run_time=0.8)
            self.play(Flash(h_a1, color=YELLOW), Circumscribe(VGroup(h_a1, h_a2), color=YELLOW), run_time=0.8)
            pulse = ValueTracker(0)
            h_a1.add_updater(lambda m, dt: m.set_stroke(width=10+3*np.sin(pulse.get_value()*4)))
            h_a2.add_updater(lambda m, dt: m.set_stroke(width=10+3*np.sin(pulse.get_value()*4)))
            self.play(pulse.animate.set_value(4.0), run_time=3.6, rate_func=linear)