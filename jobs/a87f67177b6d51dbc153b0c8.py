from manim import *
import numpy as np
import math

class AetherLabScene(Scene):
    def construct(self):
        g = 9.81
        l_val = 1.0
        th_max = 0.2
        omega = math.sqrt(g / l_val)
        T_val = 2 * math.pi * math.sqrt(l_val / g)
        t = ValueTracker(0.0)
        pivot = np.array([-3.4, 2.6, 0.0])
        rod_len = 2.3
        def theta_now():
            return th_max * math.cos(omega * t.get_value())
        def bob_point():
            th = theta_now()
            return pivot + rod_len * np.array([math.sin(th), -math.cos(th), 0.0])
        bar = Rectangle(width=3.2, height=0.18, color=GRAY, fill_opacity=1).move_to(pivot + np.array([0, 0.15, 0]))
        bar.set_z_index(1)
        eq_line = DashedLine(pivot, pivot + np.array([0, -2.7, 0]), color=BLUE, stroke_width=3, stroke_opacity=0.9)
        eq_line.set_z_index(0)
        eq_label = Text("равновесие", font_size=30, color=BLUE).scale(0.7)
        eq_label.next_to(pivot + np.array([0, -2.7, 0]), RIGHT, buff=0.15)
        eq_label.set_z_index(3)
        def make_pend():
            th = th_max * math.cos(omega * t.get_value())
            end = pivot + rod_len * np.array([math.sin(th), -math.cos(th), 0.0])
            rod = Line(pivot, end, color=WHITE, stroke_width=4)
            rod.set_z_index(2)
            bob = Dot(end, color=YELLOW, radius=0.22)
            bob.set_z_index(2)
            sup = Dot(pivot, color=GRAY, radius=0.06)
            return VGroup(rod, bob, sup)
        pend = always_redraw(make_pend)
        timer_title = Text("время качания", font_size=30, color=WHITE).scale(0.7)
        timer_title.to_edge(UP).shift(RIGHT * 2.0)
        timer_num = DecimalNumber(0.0, num_decimal_places=2, color=YELLOW)
        timer_num.scale(0.9).next_to(timer_title, DOWN, buff=0.1)
        unit_t = Text("с", font_size=30, color=WHITE).scale(0.7).next_to(timer_num, RIGHT, buff=0.15)
        timer_grp = VGroup(timer_title, timer_num, unit_t)
        # BEAT A1.B1 | 0.00-4.00 s
        self.play(LaggedStart(AnimationGroup(Create(bar), Create(eq_line), FadeIn(eq_label), FadeIn(pend)), t.animate.set_value(3.0), lag_ratio=1.0), run_time=3.6, rate_func=linear)
        self.wait(0.4)
        # BEAT A2.B1 | 4.00-7.00 s
        arc = Arc(radius=1.3, start_angle=-math.pi/2 - th_max, angle=2*th_max, arc_center=pivot, color=YELLOW, stroke_width=5)
        arc.set_z_index(2)
        amp_label = Text("амплитуда 0,2 рад", font_size=30, color=YELLOW).scale(0.7)
        amp_label.next_to(arc, DOWN, buff=0.15)
        amp_label.set_z_index(3)
        self.play(Create(arc), FadeIn(amp_label), t.animate.set_value(5.2), run_time=2.4, rate_func=linear)
        self.wait(0.6)
        # BEAT A2.B2 | 7.00-10.00 s
        small_label = Text("малые колебания", font_size=30, color=WHITE).scale(0.75)
        small_label.to_edge(DOWN).shift(LEFT * 2.0)
        small_label.set_z_index(3)
        approx = MathTex(r"\sin\theta \approx \theta", color=WHITE).scale(0.8)
        approx.next_to(small_label, UP, buff=0.15)
        approx.set_z_index(3)
        self.play(FadeOut(amp_label), FadeIn(small_label), FadeIn(approx), t.animate.set_value(7.5), run_time=2.4, rate_func=linear)
        self.wait(0.6)
        # BEAT A3.B1 | 10.00-14.00 s
        self.play(FadeOut(arc), FadeOut(approx), FadeIn(timer_grp), run_time=0.6)
        timer_num2 = DecimalNumber(0.0, num_decimal_places=2, color=YELLOW)
        timer_num2.scale(0.9).move_to(timer_num.get_center())
        self.remove(timer_num)
        timer_grp.remove(timer_num)
        timer_grp.add(timer_num2)
        timer_num = timer_num2
        self.play(FadeIn(timer_num), run_time=0.4)
        self.play(t.animate.set_value(7.5 + T_val * 1.5), timer_num.animate.set_value(T_val * 1.5), run_time=3.0, rate_func=linear)
        # BEAT A3.B2 | 14.00-18.00 s
        axes = Axes(x_range=[0, 4.2, 1], y_range=[-0.25, 0.25, 0.2], x_length=4.4, y_length=2.2).scale(0.9)
        axes.shift(RIGHT * 2.6 + DOWN * 0.4)
        axes.set_z_index(0)
        axes.set_stroke(opacity=0.35)
        xlab = Text("t", font_size=30, color=WHITE).scale(0.6).next_to(axes.x_axis, RIGHT, buff=0.1)
        ylab = Text("угол", font_size=30, color=WHITE).scale(0.6).next_to(axes.y_axis, UP, buff=0.1)
        curve = axes.plot(lambda x: th_max * math.cos(omega * x), x_range=[0, 4.2], color=YELLOW)
        curve.set_z_index(1)
        curve.set_stroke(width=4)
        sine_label = Text("угол идёт синусом", font_size=30, color=YELLOW).scale(0.7)
        sine_label.next_to(axes, UP, buff=0.2)
        sine_label.set_z_index(3)
        self.play(FadeOut(timer_grp), Create(axes), FadeIn(xlab), FadeIn(ylab), Create(curve), FadeIn(sine_label), run_time=1.2)
        dot_t0 = ValueTracker(0.0)
        live_dot = Dot(color=YELLOW, radius=0.09)
        live_dot.set_z_index(3)
        def dot_upd(m):
            xx = dot_t0.get_value()
            m.move_to(axes.c2p(xx, th_max * math.cos(omega * xx)))
        live_dot.add_updater(dot_upd)
        self.add(live_dot)
        self.play(dot_t0.animate.set_value(4.0), t.animate.set_value(7.5 + T_val * 1.5 + 2.0), run_time=2.4, rate_func=linear)
        self.wait(0.4)
        live_dot.clear_updaters()
        self.play(FadeOut(axes), FadeOut(curve), FadeOut(xlab), FadeOut(ylab), FadeOut(sine_label), FadeOut(live_dot), FadeOut(small_label), FadeOut(eq_label), FadeOut(eq_line), FadeOut(bar), run_time=0.6)
        # BEAT A4.B1 | 18.00-26.00 s
        eq1 = MathTex(r"\ddot{\theta} + \frac{g}{l}\theta = 0", color=WHITE).scale(0.9)
        eq1.move_to(ORIGIN + UP * 1.2)
        eq2 = MathTex(r"\omega_0 = \sqrt{\frac{g}{l}}", color=WHITE).scale(0.9)
        eq2.move_to(ORIGIN + UP * 0.1)
        eq3 = MathTex(r"T = 2\pi\sqrt{\frac{l}{g}}", color=WHITE).scale(1.0)
        eq3.move_to(ORIGIN + DOWN * 1.0)
        chain_label = Text("вывод периода", font_size=30, color=WHITE).scale(0.75)
        chain_label.to_edge(UP)
        chain_label.set_z_index(3)
        self.play(FadeIn(chain_label), FadeIn(eq1), t.animate.set_value(13.0), run_time=1.2, rate_func=linear)
        self.play(LaggedStart(TransformMatchingTex(eq1.copy(), eq2), TransformMatchingTex(eq2.copy(), eq3), lag_ratio=1.0), run_time=2.6)
        self.add(eq2)
        self.add(eq3)
        num_label = Text("l = 1 м даёт 2,01 с", font_size=30, color=YELLOW).scale(0.8)
        num_label.next_to(eq3, DOWN, buff=0.3)
        self.play(LaggedStart(AnimationGroup(FadeIn(num_label), t.animate.set_value(15.0)), AnimationGroup(Flash(eq3, color=YELLOW), Circumscribe(eq3, color=YELLOW)), lag_ratio=1.0), run_time=2.4, rate_func=linear)
        self.wait(0.8)
        self.play(FadeOut(chain_label), FadeOut(eq1), FadeOut(eq2), FadeOut(eq3), FadeOut(num_label), run_time=0.5)
        # BEAT A5.B1 | 26.00-30.00 s
        bar2 = Rectangle(width=2.6, height=0.16, color=GRAY, fill_opacity=1).move_to(pivot + np.array([0.6, 0.15, 0]))
        eq_line2 = DashedLine(pivot + np.array([0.6, 0, 0]), pivot + np.array([0.6, 0, 0]) + np.array([0, -2.7, 0]), color=BLUE, stroke_width=3)
        hero_formula = MathTex(r"T = 2\pi\sqrt{\frac{l}{g}} = 2.01", color=RED).scale(0.95)
        hero_formula.move_to(RIGHT * 2.6 + UP * 0.4)
        hero_formula.set_z_index(3)
        hero_sub = Text("малые колебания", font_size=30, color=WHITE).scale(0.75)
        hero_sub.next_to(hero_formula, DOWN, buff=0.25)
        hero_sub.set_z_index(3)
        hero_l = Text("l = 1 м", font_size=30, color=YELLOW).scale(0.75)
        hero_l.next_to(hero_formula, UP, buff=0.25)
        hero_grp = VGroup(hero_formula, hero_sub, hero_l)
        hero_grp.scale_to_fit_width(config.frame_width - 7.5)
        hero_grp.move_to(RIGHT * 2.8 + UP * 0.2)
        self.play(FadeIn(bar2), FadeIn(eq_line2), FadeIn(hero_grp), run_time=0.8)
        self.play(Flash(hero_formula, color=RED), Circumscribe(hero_formula, color=RED), t.animate.set_value(17.5), run_time=1.0)
        self.play(t.animate.set_value(21.5), LaggedStart(hero_formula.animate.scale(1.06), hero_formula.animate.scale(1/1.06), lag_ratio=1.0), run_time=1.8, rate_func=linear)
        self.wait(0.4)