from manim import *
import numpy as np

class AetherLabScene(Scene):
    def construct(self):
            # BEAT A1.B1 | 0.00-4.00 s
            surface = Rectangle(width=11, height=0.5, fill_color=GRAY_D, fill_opacity=0.9, stroke_color=GRAY_B, stroke_opacity=0.6)
            surface.to_edge(DOWN, buff=0.6)
            surface.set_z_index(0)
            block = Rectangle(width=1.6, height=1.0, fill_color=TEAL, fill_opacity=1, stroke_color=WHITE, stroke_width=3)
            block.move_to(surface.get_top() + UP * 0.5 + LEFT * 2.5)
            block.set_z_index(2)
            ruler = NumberLine(x_range=[-6, 6, 1], length=10, include_numbers=False, stroke_opacity=0.35)
            ruler.next_to(surface, UP, buff=0.05)
            ruler.set_z_index(0)
            label_m = Text("масса 2 кг", font_size=30, color=WHITE)
            label_m.next_to(block, UP, buff=0.25)
            label_m.set_z_index(3)
            table_group = VGroup(surface, ruler, block, label_m)
            self.play(LaggedStart(FadeIn(surface), FadeIn(ruler), GrowFromCenter(block), FadeIn(label_m, shift=UP * 0.2), lag_ratio=0.25), run_time=1.2)
            self.wait(2.3)
            # BEAT A2.B1 | 4.00-7.00 s
            arrow = Arrow(start=block.get_left() + LEFT * 2.2, end=block.get_left() + LEFT * 0.1, buff=0, color=ORANGE, stroke_width=10, max_tip_length_to_length_ratio=0.2)
            arrow.set_z_index(2)
            label_F = Text("F = 6 Н", font_size=32, color=ORANGE)
            label_F.next_to(arrow, UP, buff=0.2)
            label_F.set_z_index(3)
            self.play(GrowArrow(arrow), FadeIn(label_F, shift=DOWN * 0.2), run_time=1.0)
            self.wait(1.6)
            # BEAT A2.B2 | 7.00-10.00 s
            eq_law = MathTex("F", "=", "m", "a", font_size=44)
            eq_law.to_edge(UP, buff=0.4)
            eq_law.set_z_index(3)
            law_caption = Text("второй закон Ньютона", font_size=30, color=TEAL)
            law_caption.next_to(eq_law, DOWN, buff=0.15)
            self.play(FadeIn(eq_law, shift=DOWN * 0.2), FadeIn(law_caption, shift=DOWN * 0.2), run_time=1.0)
            self.wait(1.6)
            # BEAT A3.B1 | 10.00-14.00 s
            v_title = Text("скорость v растёт", font_size=30, color=WHITE)
            v_title.to_edge(UP, buff=1.6)
            v_tracker = ValueTracker(0.0)
            v_num = DecimalNumber(0.0, num_decimal_places=1, color=WHITE, font_size=40)
            v_unit = Text("м/с", font_size=30, color=WHITE)
            v_readout = VGroup(v_num, v_unit)
            v_readout.arrange(RIGHT, buff=0.15)
            v_readout.next_to(block, DOWN, buff=0.15)
            v_readout.move_to([block.get_center()[0], surface.get_top()[1] - 0.55, 0])
            self.play(FadeIn(v_title, shift=UP * 0.2), FadeIn(v_num), FadeIn(v_unit), run_time=0.6)
            v_num.add_updater(lambda m: m.set_value(v_tracker.get_value()))
            start_x = block.get_center()[0]
            self.play(block.animate.move_to([start_x + 3.2, block.get_center()[1], 0]), arrow.animate.move_to([start_x + 3.2 - 1.25, arrow.get_center()[1], 0]), label_F.animate.next_to(arrow, UP, buff=0.2), v_tracker.animate.set_value(6.0), run_time=2.6, rate_func=rate_functions.ease_in_quad)
            v_num.clear_updaters()
            self.wait(0.4)
            motion_group = VGroup(block, arrow, label_F, label_m, v_num, v_unit, v_title, ruler, law_caption)
            # BEAT A3.B2 | 14.00-18.00 s
            self.play(FadeOut(motion_group), run_time=0.4)
            axes = Axes(x_range=[0, 5, 1], y_range=[0, 15, 5], x_length=6.5, y_length=3.6, axis_config={"stroke_opacity": 0.35})
            axes.move_to(DOWN * 0.6)
            axes.set_z_index(0)
            x_lab = Text("t, с", font_size=30, color=WHITE)
            x_lab.next_to(axes.x_axis, DOWN, buff=0.25)
            y_lab = Text("v, м/с", font_size=30, color=WHITE)
            y_lab.next_to(axes.y_axis, LEFT, buff=0.3)
            line = axes.plot(lambda t: 3.0 * t, x_range=[0, 5], color=TEAL)
            line.set_z_index(2)
            line_label = Text("скорость растёт по прямой", font_size=30, color=TEAL)
            line_label.next_to(axes, UP, buff=0.25)
            tg = ValueTracker(0.0)
            dot = Dot(color=ORANGE, radius=0.09)
            dot.set_z_index(3)
            dot.add_updater(lambda m: m.move_to(axes.c2p(tg.get_value(), 3.0 * tg.get_value())))
            self.play(AnimationGroup(Create(axes), FadeIn(x_lab), FadeIn(y_lab), FadeIn(line_label, shift=DOWN * 0.2), Create(line), lag_ratio=0.2), run_time=2.2)
            self.add(dot)
            self.play(tg.animate.set_value(5.0), run_time=1.2, rate_func=linear)
            dot.clear_updaters()
            self.wait(0.2)
            graph_group = VGroup(axes, x_lab, y_lab, line, line_label, dot)
            # BEAT A4.B1 | 18.00-25.00 s
            self.play(FadeOut(graph_group), FadeOut(surface), run_time=0.4)
            eq1 = MathTex("a", "=", "{{F}}", "\\over", "{{m}}", font_size=52)
            eq1.move_to(UP * 0.8)
            calc_caption = Text("считаем ускорение", font_size=30, color=WHITE)
            calc_caption.next_to(eq1, UP, buff=0.25)
            self.play(FadeIn(eq1), FadeIn(calc_caption, shift=DOWN * 0.2), run_time=0.8)
            self.wait(0.6)
            eq2 = MathTex("a", "=", "{{6}}", "\\over", "{{2}}", font_size=52)
            eq2.move_to(eq1.get_center())
            self.play(TransformMatchingTex(eq1, eq2), run_time=1.0)
            self.wait(0.8)
            eq3 = MathTex("a", "=", "3", r"\text{ m/s}^2", font_size=56)
            eq3.move_to(eq2.get_center())
            self.play(TransformMatchingTex(eq2, eq3), run_time=1.0)
            answer_tag = Text("ускорение 3 м/с²", font_size=34, color=WHITE)
            answer_tag.next_to(eq3, DOWN, buff=0.4)
            self.play(FadeIn(answer_tag, shift=UP * 0.2), Flash(eq3, color=ORANGE), run_time=0.9)
            self.wait(1.5)
            eq_group = VGroup(eq_law, eq3, answer_tag, calc_caption)
            # BEAT A5.B1 | 25.00-30.00 s
            self.play(FadeOut(eq_group), run_time=0.4)
            hero_surface = Rectangle(width=11, height=0.5, fill_color=GRAY_D, fill_opacity=0.9, stroke_color=GRAY_B, stroke_opacity=0.6)
            hero_surface.to_edge(DOWN, buff=0.6)
            hero_surface.set_z_index(0)
            hero_block = Rectangle(width=1.6, height=1.0, fill_color=TEAL, fill_opacity=1, stroke_color=WHITE, stroke_width=3)
            hero_block.move_to(hero_surface.get_top() + UP * 0.5 + LEFT * 1.5)
            hero_block.set_z_index(2)
            hero_arrow = Arrow(start=hero_block.get_left() + LEFT * 2.2, end=hero_block.get_left() + LEFT * 0.1, buff=0, color=ORANGE, stroke_width=12, max_tip_length_to_length_ratio=0.2)
            hero_arrow.set_z_index(2)
            hero_F = Text("F = 6 Н", font_size=32, color=ORANGE)
            hero_F.next_to(hero_arrow, UP, buff=0.2)
            hero_formula = MathTex("F", "=", "m", "a", font_size=44)
            hero_formula.to_edge(UP, buff=0.35)
            hero_a = MathTex("a", "=", "3", r"\text{ m/s}^2", font_size=60, color=YELLOW)
            hero_a.next_to(hero_formula, DOWN, buff=0.25)
            hero_v_lab = Text("v растёт", font_size=30, color=WHITE)
            hero_v_lab.next_to(hero_a, DOWN, buff=0.25)
            hero_group = VGroup(hero_surface, hero_block, hero_arrow, hero_F, hero_formula, hero_a, hero_v_lab)
            hero_group.scale_to_fit_width(12.0)
            hero_group.move_to(ORIGIN * 0.2)
            self.play(LaggedStart(FadeIn(hero_group, shift=UP * 0.2), Flash(hero_arrow), Circumscribe(hero_a, color=YELLOW), lag_ratio=0.4), run_time=1.8)
            idle_t = ValueTracker(0.0)
            hero_arrow.add_updater(lambda m: m.set_opacity(0.65 + 0.35 * np.sin(idle_t.get_value() * 4.0)))
            hero_a.add_updater(lambda m: m.set_opacity(0.75 + 0.25 * np.sin(idle_t.get_value() * 3.0 + 1.0)))
            self.play(idle_t.animate.set_value(6.0), run_time=2.4, rate_func=linear)
            hero_arrow.clear_updaters()
            hero_a.clear_updaters()