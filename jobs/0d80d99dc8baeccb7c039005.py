from manim import *
import numpy as np

class AetherLabScene(Scene):
    def construct(self):
        E_VAL = 98.0
        V_VAL = 9.899494936611665
        TOP = np.array([-4.0, 2.0, 0.0])
        BOT = np.array([-0.5, -1.5, 0.0])
        prog = ValueTracker(0.0)
        idle = ValueTracker(0.0)
        # BEAT A1.B1 | 0.00-4.00 s
        hill = Polygon(TOP, BOT, np.array([-4.0, -1.5, 0.0]), color=BLUE, fill_opacity=0.35, stroke_color=BLUE, stroke_opacity=0.9)
        hill.set_z_index(0)
        ground = Line(np.array([-6.0, -1.5, 0.0]), np.array([6.0, -1.5, 0.0]), color=WHITE, stroke_width=4)
        block0 = Square(side_length=0.55, color=WHITE, fill_opacity=1.0).move_to(TOP + np.array([0.3, 0.35, 0.0]))
        block0.set_z_index(2)
        h_arrow = DoubleArrow(np.array([-5.2, -1.5, 0.0]), np.array([-5.2, 2.0, 0.0]), color=BLUE, stroke_width=4, buff=0.05)
        h_label = Text("h = 5 м", font_size=30, color=WHITE).next_to(h_arrow, LEFT, buff=0.15)
        m_label = Text("брусок 2 кг", font_size=30, color=WHITE).next_to(block0, UP, buff=0.15)
        m_label.set_z_index(3)
        self.play(LaggedStart(Create(hill), Create(ground), Create(h_arrow), FadeIn(block0, scale=0.5), FadeIn(h_label), FadeIn(m_label), lag_ratio=0.12), run_time=1.2)
        self.wait(2.5)
        # BEAT A2.B1 | 4.00-7.00 s
        eq_pe_form = MathTex(r"E = mgh = 98", color=WHITE, font_size=34)
        eq_pe_unit = Text("Дж", font_size=30, color=WHITE)
        eq_pe = VGroup(eq_pe_form, eq_pe_unit)
        eq_pe.arrange(RIGHT, buff=0.15)
        eq_pe.next_to(block0, UP, buff=0.6)
        eq_pe.move_to(np.array([-2.2, 2.9, 0.0]))
        pe_tag = Text("запас высоты", font_size=30, color=BLUE).next_to(eq_pe, UP, buff=0.12)
        pe_bar_bg = Rectangle(width=0.5, height=2.0, color=BLUE, stroke_opacity=0.5).move_to(np.array([3.2, 0.0, 0.0]))
        pe_fill_static = Rectangle(width=0.5, height=2.0, color=BLUE, fill_opacity=0.9, stroke_width=0).move_to(pe_bar_bg.get_center())
        pe_cap = Text("98 Дж", font_size=30, color=WHITE).next_to(pe_bar_bg, UP, buff=0.12)
        self.play(FadeIn(eq_pe), FadeIn(pe_tag, shift=DOWN*0.2), FadeIn(pe_bar_bg), FadeIn(pe_fill_static), FadeIn(pe_cap), run_time=0.8)
        self.wait(1.9)
        # BEAT A2.B2 | 7.00-10.00 s
        eq_ke = MathTex(r"E_k = \frac{mv^2}{2}", color=WHITE, font_size=34)
        eq_ke.move_to(np.array([3.4, 2.9, 0.0]))
        ke_bar_bg = Rectangle(width=0.5, height=2.0, color=ORANGE, stroke_opacity=0.5).move_to(np.array([4.6, 0.0, 0.0]))
        ke_fill_empty = Rectangle(width=0.5, height=0.02, color=ORANGE, fill_opacity=0.9, stroke_width=0).move_to(np.array([4.6, -0.99, 0.0]))
        ke_cap = Text("скорость ждёт", font_size=30, color=WHITE).next_to(ke_bar_bg, UP, buff=0.12)
        ke_cap.scale(0.9)
        self.play(FadeIn(eq_ke), FadeIn(ke_bar_bg), FadeIn(ke_fill_empty), FadeIn(ke_cap), run_time=0.8)
        self.wait(1.9)
        # BEAT A3.B1 | 10.00-14.00 s
        self.remove(block0, pe_fill_static, ke_fill_empty, pe_cap, ke_cap)
        def make_dynamic():
            p = float(np.clip(prog.get_value(), 0.0, 1.0))
            pos = (1.0 - p) * TOP + p * BOT + np.array([0.3, 0.35 * (1.0 - p) + 0.32 * p, 0.0])
            blk = Square(side_length=0.55, color=WHITE, fill_opacity=1.0).move_to(pos)
            pe_h = 2.0 * (1.0 - p)
            ke_h = 2.0 * p
            pe_f = Rectangle(width=0.5, height=max(pe_h, 0.02), color=BLUE, fill_opacity=0.9, stroke_width=0)
            pe_f.move_to(np.array([3.2, -1.0 + max(pe_h, 0.02) / 2.0, 0.0]))
            ke_f = Rectangle(width=0.5, height=max(ke_h, 0.02), color=ORANGE, fill_opacity=0.9, stroke_width=0)
            ke_f.move_to(np.array([4.6, -1.0 + max(ke_h, 0.02) / 2.0, 0.0]))
            pe_n = DecimalNumber(E_VAL * (1.0 - p), num_decimal_places=0, color=WHITE, font_size=28)
            pe_n.next_to(np.array([3.2, 1.0, 0.0]), UP, buff=0.12)
            ke_n = DecimalNumber(E_VAL * p, num_decimal_places=0, color=WHITE, font_size=28)
            ke_n.next_to(np.array([4.6, 1.0, 0.0]), UP, buff=0.12)
            move_tag = Text("высота в движение", font_size=30, color=WHITE).move_to(np.array([0.2, 2.9, 0.0]))
            return VGroup(blk, pe_f, ke_f, pe_n, ke_n, move_tag)
        dyn = always_redraw(make_dynamic)
        self.add(dyn)
        self.play(prog.animate.set_value(0.75), run_time=3.2, rate_func=smooth)
        self.wait(0.5)
        # BEAT A3.B2 | 14.00-18.00 s
        v_label_static = Text("v растёт", font_size=30, color=WHITE).move_to(np.array([2.2, -2.4, 0.0]))
        v_num_static = DecimalNumber(0.0, num_decimal_places=1, color=WHITE, font_size=40)
        v_num_static.next_to(v_label_static, RIGHT, buff=0.2)
        v_unit = Text("м/с", font_size=30, color=WHITE).next_to(v_num_static, RIGHT, buff=0.15)
        v_unit.add_updater(lambda m: m.next_to(v_num_static, RIGHT, buff=0.15))
        v_num_static.add_updater(lambda m: m.set_value(V_VAL * np.sqrt(np.clip(prog.get_value(), 0.0, 1.0))))
        self.play(FadeIn(v_label_static), FadeIn(v_num_static), FadeIn(v_unit), run_time=0.6)
        self.play(prog.animate.set_value(1.0), run_time=2.6, rate_func=linear)
        self.wait(0.5)
        v_num_static.clear_updaters()
        v_unit.clear_updaters()
        # BEAT A4.B1 | 18.00-21.27 s
        self.play(FadeOut(dyn), FadeOut(eq_pe), FadeOut(eq_ke), FadeOut(pe_tag), FadeOut(pe_bar_bg), FadeOut(ke_bar_bg), FadeOut(v_label_static), FadeOut(v_num_static), FadeOut(v_unit), FadeOut(h_label), FadeOut(h_arrow), FadeOut(m_label), FadeOut(hill), FadeOut(ground), run_time=0.5)
        eq1 = MathTex(r"mgh = \frac{mv^2}{2}", color=WHITE, font_size=44)
        eq1.move_to(ORIGIN)
        eq1_tag = Text("энергии равны", font_size=30, color=WHITE).next_to(eq1, UP, buff=0.3)
        num_tag = Text("98 Дж наверху", font_size=30, color=WHITE).next_to(eq1, DOWN, buff=0.3)
        self.play(FadeIn(eq1), FadeIn(eq1_tag), FadeIn(num_tag), run_time=0.8)
        self.play(Flash(eq1, color=WHITE), run_time=0.4)
        self.wait(1.5)
        # BEAT A4.B2 | 21.27-25.00 s
        eq2_form = MathTex(r"v = \sqrt{2gh} = 9.9", color=WHITE, font_size=40)
        eq2_unit = Text("м/с", font_size=30, color=WHITE)
        eq2 = VGroup(eq2_form, eq2_unit)
        eq2.arrange(RIGHT, buff=0.15)
        eq2.move_to(ORIGIN)
        self.play(Transform(eq1, eq2), FadeOut(num_tag), run_time=0.9)
        eq2_tag = Text("корень из двух же аш", font_size=30, color=WHITE).next_to(eq2, UP, buff=0.3)
        self.play(FadeIn(eq2_tag), run_time=0.5)
        self.wait(2.0)
        # BEAT A5.B1 | 25.00-30.00 s
        self.play(FadeOut(eq1), FadeOut(eq2), FadeOut(eq1_tag), FadeOut(eq2_tag), run_time=0.4)
        hero_block = Square(side_length=0.7, color=WHITE, fill_opacity=1.0).move_to(np.array([-2.5, -1.0, 0.0]))
        hero_h = Text("h = 5 м тает", font_size=30, color=WHITE).next_to(hero_block, LEFT, buff=0.4)
        hero_form = MathTex(r"v = \sqrt{2gh}", color=YELLOW, font_size=44)
        hero_line = Text("98 Дж → v = 9,9 м/с", font_size=32, color=YELLOW)
        hero_group = VGroup(hero_form, hero_line)
        hero_group.arrange(DOWN, buff=0.25)
        hero_group.move_to(np.array([2.0, -0.3, 0.0]))
        hero_group.scale_to_fit_width(5.0)
        hero_group.move_to(np.array([2.0, -0.3, 0.0]))
        hero_title = Text("высота стала скоростью", font_size=32, color=WHITE).move_to(np.array([0.0, 2.6, 0.0]))
        hero_bar_bg = Rectangle(width=3.0, height=0.5, color=ORANGE, stroke_opacity=0.6).move_to(np.array([2.0, -1.8, 0.0]))
        self.play(FadeIn(hero_block), FadeIn(hero_h), FadeIn(hero_form), FadeIn(hero_line), FadeIn(hero_title), FadeIn(hero_bar_bg), run_time=0.9)
        self.play(LaggedStart(Flash(hero_form), Circumscribe(hero_form, color=YELLOW), lag_ratio=0.1), run_time=0.8)
        def hero_pulse():
            s = 1.0 + 0.06 * np.sin(idle.get_value() * 4.0)
            bar = Rectangle(width=3.0 * s, height=0.5, color=ORANGE, fill_opacity=0.9, stroke_width=0).move_to(hero_bar_bg.get_center())
            wob = 0.08 * np.sin(idle.get_value() * 3.0)
            lab = Text("98 Дж → v = 9,9 м/с", font_size=32, color=YELLOW).move_to(np.array([2.0, -0.85 + wob, 0.0]))
            return VGroup(bar, lab)
        pulser = always_redraw(hero_pulse)
        hero_line.clear_updaters()
        self.add(pulser)
        self.play(idle.animate.set_value(6.0), run_time=2.6, rate_func=linear)