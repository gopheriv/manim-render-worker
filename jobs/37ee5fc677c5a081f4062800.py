from manim import *
import numpy as np
import math

class AetherLabScene(Scene):
    def construct(self):
            g = 9.81
            l_val = 1.0
            th_max = 0.2
            omega0 = math.sqrt(g / l_val)
            T_val = 2 * math.pi * math.sqrt(l_val / g)
            t = ValueTracker(0.0)
            pivot = np.array([0.0, 2.6, 0.0])
            rod_len = 2.4
            def theta_at(tt):
                return th_max * math.cos(omega0 * tt)
            def bob_point(th):
                return pivot + rod_len * np.array([math.sin(th), -math.cos(th), 0.0])
            support = Line(pivot + LEFT * 1.6, pivot + RIGHT * 1.6, color=GRAY_B, stroke_width=6)
            support.set_z_index(1)
            mount = Dot(pivot, color=WHITE, radius=0.06)
            mount.set_z_index(4)
            def make_pendulum():
                th = theta_at(t.get_value())
                bp = bob_point(th)
                rod = Line(pivot, bp, color=BLUE_B, stroke_width=5)
                rod.set_z_index(2)
                bob = Dot(bp, color=YELLOW, radius=0.18)
                bob.set_z_index(3)
                return VGroup(rod, bob)
            pend = always_redraw(make_pendulum)
            title = Text("Маятник", color=WHITE, font_size=34).to_edge(UP, buff=0.25)
            title.set_z_index(5)
            # BEAT A1.B1 | 0.00-4.00 s
            lab1 = Text("Маятник l = 1,0 м", color=WHITE, font_size=30).next_to(support, UP, buff=0.35)
            lab1.set_z_index(5)
            self.add(support, mount, pend)
            self.play(AnimationGroup(Write(title), FadeIn(support), FadeIn(mount), FadeIn(lab1), run_time=1.4))
            self.play(t.animate.set_value(3.2), run_time=2.0, rate_func=linear)
            self.wait(0.3)
            # BEAT A2.B1 | 4.00-7.00 s
            eq_line_end = pivot + DOWN * (rod_len + 0.5)
            equil = DashedLine(pivot, eq_line_end, color=GRAY, dash_length=0.12)
            equil.set_z_index(1)
            equil.set_stroke(opacity=0.6)
            arc = Arc(radius=1.4, start_angle=-90 * DEGREES - th_max, angle=2 * th_max, arc_center=pivot, color=YELLOW, stroke_width=4)
            arc.set_z_index(2)
            lab_arc = Text("равновесие и θmax = 0,2 рад", color=WHITE, font_size=30).to_edge(DOWN, buff=0.4)
            lab_arc.set_z_index(5)
            self.play(AnimationGroup(Create(equil), Create(arc), FadeIn(lab_arc), t.animate.set_value(5.2), run_time=2.5, rate_func=linear))
            self.wait(0.2)
            # BEAT A2.B2 | 7.00-10.00 s
            eq1 = MathTex(r"\ddot{\theta} + \frac{g}{l}\theta = 0", color=WHITE, font_size=40)
            eq1.to_edge(DOWN, buff=0.4)
            eq1.set_z_index(5)
            tag1 = Text("малые углы", color=WHITE, font_size=30).next_to(eq1, UP, buff=0.15)
            tag1.set_z_index(5)
            grp_eq = VGroup(tag1, eq1)
            self.play(AnimationGroup(FadeOut(lab_arc), Write(eq1), FadeIn(tag1), run_time=1.2))
            self.play(t.animate.set_value(6.6), run_time=1.5, rate_func=linear)
            self.wait(0.3)
            # BEAT A3.B1 | 10.00-14.00 s
            ang_label = Text("θ =", color=WHITE, font_size=32).to_edge(DOWN, buff=0.45).shift(LEFT * 2.2)
            ang_label.set_z_index(5)
            ang_num = DecimalNumber(theta_at(t.get_value()), num_decimal_places=3, color=YELLOW, font_size=36)
            ang_num.next_to(ang_label, RIGHT, buff=0.15)
            ang_num.set_z_index(5)
            ang_num.add_updater(lambda m: m.set_value(theta_at(t.get_value())))
            g_label = Text("g = 9,81 м/с²", color=WHITE, font_size=30).to_edge(DOWN, buff=0.45).shift(RIGHT * 2.2)
            g_label.set_z_index(5)
            self.play(AnimationGroup(FadeOut(grp_eq), FadeOut(lab1), FadeOut(equil), FadeOut(arc), FadeIn(ang_label), FadeIn(ang_num), FadeIn(g_label), run_time=1.1))
            self.play(t.animate.set_value(10.6), run_time=2.8, rate_func=linear)
            self.wait(0.2)
            # BEAT A3.B2 | 14.00-18.00 s
            ang_num.clear_updaters()
            clock_label = Text("t =", color=WHITE, font_size=32).to_edge(DOWN, buff=0.45).shift(LEFT * 2.0)
            clock_label.set_z_index(5)
            t0 = t.get_value()
            clock_num = DecimalNumber(0.0, num_decimal_places=2, color=WHITE, font_size=36)
            clock_num.next_to(clock_label, RIGHT, buff=0.15)
            clock_num.set_z_index(5)
            clock_num.add_updater(lambda m: m.set_value(t.get_value() - t0))
            period_tag = Text("одно колебание", color=WHITE, font_size=30).to_edge(DOWN, buff=0.45).shift(RIGHT * 2.2)
            period_tag.set_z_index(5)
            self.play(AnimationGroup(FadeOut(ang_label), FadeOut(ang_num), FadeOut(g_label), FadeIn(clock_label), FadeIn(clock_num), FadeIn(period_tag), run_time=1.0))
            self.play(t.animate.set_value(t0 + T_val), run_time=2.8, rate_func=linear)
            self.wait(0.2)
            # BEAT A4.B1 | 18.00-22.23 s
            clock_num.clear_updaters()
            eq_a = MathTex(r"\omega_0 = \sqrt{\frac{g}{l}}", color=WHITE, font_size=42)
            eq_a.to_edge(DOWN, buff=0.5)
            eq_a.set_z_index(5)
            self.play(AnimationGroup(FadeOut(clock_label), FadeOut(clock_num), FadeOut(period_tag), Write(eq_a), run_time=1.1))
            self.wait(0.4)
            eq_b = MathTex(r"T = 2\pi\sqrt{\frac{l}{g}}", color=WHITE, font_size=42)
            eq_b.to_edge(DOWN, buff=0.5)
            eq_b.set_z_index(5)
            self.play(AnimationGroup(TransformMatchingTex(eq_a, eq_b), t.animate.set_value(t.get_value() + 1.5), run_time=2.4, rate_func=linear))
            # BEAT A4.B2 | 22.23-26.00 s
            eq_c = MathTex(r"T = 2\pi\sqrt{1.0/9.81} \approx 2.01\,\text{s}", color=WHITE, font_size=38)
            eq_c.to_edge(DOWN, buff=0.5)
            eq_c.set_z_index(5)
            self.play(AnimationGroup(TransformMatchingTex(eq_b, eq_c), t.animate.set_value(t.get_value() + 1.5), run_time=3.47, rate_func=linear))
            self.wait(0.3)
            # BEAT A5.B1 | 26.00-30.00 s
            pend.clear_updaters()
            self.remove(pend)
            t.set_value(0.0)
            hero_pend = always_redraw(make_pendulum)
            hero_form = MathTex(r"T \approx 2.01\,\text{s}", color=RED, font_size=52)
            hero_form.to_edge(LEFT, buff=0.6).shift(UP * 0.3)
            hero_form.set_z_index(5)
            hero_note = Text("Период около двух секунд", color=WHITE, font_size=30).to_edge(DOWN, buff=0.4)
            hero_note.set_z_index(5)
            hero_group = VGroup(hero_form, hero_note)
            self.play(AnimationGroup(FadeOut(eq_c), FadeOut(title), FadeOut(support), FadeOut(mount), FadeIn(hero_pend), FadeIn(hero_form), FadeIn(hero_note), run_time=1.2))
            self.play(AnimationGroup(Flash(hero_form, color=RED), Circumscribe(hero_form, color=RED), run_time=0.8))
            self.play(t.animate.set_value(3.0), run_time=2.0, rate_func=linear)
            self.wait(0.2)